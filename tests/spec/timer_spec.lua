local timer = require("src.systems.timer")

describe("Timer system", function()

    describe("constructor (v0.6.1 regression)", function()
        it("applies mode and duration to the public fields update() reads", function()
            local t = timer.new({ mode = "stopwatch", duration = 5 })
            assert.equals("stopwatch", t.mode)
            assert.equals(5, t.duration)
        end)

        it("defaults to countdown mode with 1s duration", function()
            local t = timer.new()
            assert.equals("countdown", t.mode)
            assert.equals(1, t.duration)
        end)

        it("stopwatch mode never expires even after many updates", function()
            local t = timer.new({ mode = "stopwatch" })
            for _ = 1, 10 do t:update(1) end
            assert.is_false(t:isExpired())
            assert.is_nil(t:getRemaining())
            assert.is_nil(t:getProgress())
        end)
    end)

    it("counts down and fires tick each step, expired exactly once", function()
        local t = timer.new({ duration = 1 })
        local expired = 0
        local lastRemaining
        t:on("tick", function(_, remaining) lastRemaining = remaining end)
        t:on("expired", function() expired = expired + 1 end)

        t:update(0.4)
        assert.is_true(math.abs(lastRemaining - 0.6) < 1e-9)

        t:update(0.6)
        assert.equals(1, expired)
        assert.is_true(t:isExpired())
        assert.equals(0, t:getRemaining())

        t:update(1)
        assert.equals(1, expired)
    end)

    it("pause stops advancing and resume continues from the same point", function()
        local t = timer.new({ duration = 2 })
        t:update(0.5)
        t:pause()
        t:update(1)
        assert.equals(0.5, t:getElapsed())
        t:resume()
        t:update(0.25)
        assert.equals(0.75, t:getElapsed())
        assert.is_true(t:isRunning())
    end)

    it("resume on an expired countdown restarts it", function()
        local t = timer.new({ duration = 0.5 })
        t:update(1)
        assert.is_true(t:isExpired())
        t:resume()
        assert.is_false(t:isExpired())
        assert.equals(0, t:getElapsed())
        assert.is_true(t:isRunning())
    end)

    it("getProgress goes from 0 to 1 and clamps", function()
        local t = timer.new({ duration = 2 })
        assert.equals(0, t:getProgress())
        t:update(1)
        assert.equals(0.5, t:getProgress())
        t:update(5)
        assert.equals(1, t:getProgress())
    end)

    it("reset clears elapsed, expired and paused state", function()
        local t = timer.new({ duration = 1 })
        t:update(1)
        t:pause()
        t:reset()
        assert.equals(0, t:getElapsed())
        assert.is_false(t:isExpired())
        assert.is_true(t:isRunning())
    end)

    it("ignores non-positive dt", function()
        local t = timer.new({ duration = 1 })
        t:update(0)
        t:update(-1)
        assert.equals(0, t:getElapsed())
    end)

end)
